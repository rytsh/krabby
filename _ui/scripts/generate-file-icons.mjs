import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { FILE_ICON_NAMES } from "../src/lib/file-icons.js";

const require = createRequire(import.meta.url);
const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const outputPath = resolve(scriptDirectory, "../src/lib/file-icons.generated.js");
const sourcePath = require.resolve("@iconify-json/vscode-icons/icons.json");
const source = JSON.parse(await readFile(sourcePath, "utf8"));

const missing = FILE_ICON_NAMES.filter((name) => !source.icons[name]);
if (missing.length > 0) {
  throw new Error(`Missing vscode-icons entries: ${missing.join(", ")}`);
}

const collection = {
  prefix: source.prefix,
  width: source.width,
  height: source.height,
  icons: Object.fromEntries(FILE_ICON_NAMES.map((name) => [name, source.icons[name]])),
};
const output = `// Generated by pnpm generate:icons. Do not edit manually.\nexport const vscodeIcons = ${JSON.stringify(collection, null, 2)};\n`;

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== output) {
    console.error("File icon subset is stale. Run `pnpm generate:icons`.");
    process.exitCode = 1;
  } else {
    console.log(`File icon subset is current (${FILE_ICON_NAMES.length} icons).`);
  }
} else {
  await writeFile(outputPath, output);
  console.log(`Generated ${FILE_ICON_NAMES.length} icons at ${outputPath}.`);
}
